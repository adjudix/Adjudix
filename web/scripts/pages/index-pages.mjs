// Lists every static page of the public site in src/lib/pages/loaders.ts,
// so the console can open any of them in the page editor. Runs before
// `next dev` and `next build`; a test checks the list is current.
//
//   node scripts/pages/index-pages.mjs          regenerate the list
//   node scripts/pages/index-pages.mjs --wrap   also make new pages editable:
//     their default export goes through editablePage() and their metadata
//     through editableMetadata(), so a page published in the console
//     replaces them.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "../..");
const SITE = path.join(ROOT, "src/app/(site)");
const OUT = path.join(ROOT, "src/lib/pages/loaders.ts");

function pages(dir, route = "") {
  const found = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isFile() && entry.name === "page.tsx") found.push({ file: path.join(dir, entry.name), route: route || "/" });
    if (!entry.isDirectory() || /^[[@_]/.test(entry.name)) continue;
    const segment = entry.name.startsWith("(") ? "" : `/${entry.name}`;
    found.push(...pages(path.join(dir, entry.name), `${route}${segment}`));
  }
  return found;
}

export function listPages() {
  return pages(SITE)
    .filter((page) => !page.route.startsWith("/apply"))
    .sort((a, b) => a.route.localeCompare(b.route));
}

export function loadersSource(list = listPages()) {
  const lines = list.map(({ file, route }) => {
    const folder = path.relative(SITE, path.dirname(file)).split(path.sep).join("/");
    const spec = `@/app/(site)/${folder ? `${folder}/` : ""}page`;
    return `  ${JSON.stringify(route)}: () => import(${JSON.stringify(spec)}),`;
  });
  return `// Generated by scripts/pages/index-pages.mjs — do not edit by hand.
// Every static page of the public site, loaded on demand by the console.
export const PAGE_LOADERS: Record<string, () => Promise<unknown>> = {
${lines.join("\n")}
};
`;
}

function wrap({ file, route }) {
  let source = readFileSync(file, "utf8");
  if (source.includes("editablePage(")) return false;
  const exported = source.match(/export default (async )?function (\w+)\s*\(/);
  if (!exported) return false;
  const name = exported[2];
  source = source.replace(exported[0], `${exported[1] ?? ""}function ${name}(`);
  const hasMetadata = /export const metadata(: Metadata)? =/.test(source);
  if (hasMetadata) source = source.replace(/export const metadata(: Metadata)? =/, "const metadata$1 =");
  source = `import { editableMetadata, editablePage } from "@/lib/pages/editable";\n${source}`;
  source = source.trimEnd() + `\n\n// The console can replace this page with blocks (see lib/pages/editable).\n`;
  if (hasMetadata) source += `export const generateMetadata = editableMetadata(${JSON.stringify(route)}, metadata);\n`;
  source += `export default editablePage(${JSON.stringify(route)}, ${name}${hasMetadata ? ", metadata" : ""});\n`;
  if (!hasMetadata) source = source.replace("import { editableMetadata, editablePage }", "import { editablePage }");
  writeFileSync(file, source);
  return true;
}

// Run as a script (not when a test imports listPages / loadersSource).
if (process.argv[1]?.endsWith("index-pages.mjs")) {
  const list = listPages();
  if (process.argv.includes("--wrap")) {
    const wrapped = list.filter((page) => !/\[/.test(page.route) && wrap(page));
    console.log(`[pages] made ${wrapped.length} pages editable`);
  }
  const editable = list.filter((page) => readFileSync(page.file, "utf8").includes("editablePage("));
  writeFileSync(OUT, loadersSource(editable));
  console.log(`[pages] indexed ${editable.length} pages`);
}
